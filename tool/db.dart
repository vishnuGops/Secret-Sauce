/// Actions that destroy data and therefore require an explicit `--yes`.
const _destructive = {'sim:clean', 'purge:fake', 'purge:fake:rows'};

/// Actions that write a lot to a database that is probably not this machine's,
/// and therefore also require `--yes` — with a different reason than
/// [_destructive], so they get their own message rather than being told they
/// delete `auth.users` rows, which they do not.
///
/// Nothing here is reversible in the sense that matters: the free tier has no
/// PITR, so the undo for a bad deploy is the dump `db:backup` took beforehand.
const _needsConfirmation = {'hosted:deploy'};

/// The two dumps a restorable backup needs (B087, Phase 32f5).
///
/// **`--schema=public` alone is not a backup of this project.** Every
/// `profiles.id` is an FK to `auth.users`, so a public-only dump restores into a
/// project whose accounts do not exist: the restore itself fails on the FK, and
/// if it did not, the result would be a vault of recipes nobody can sign in to
/// own. The free tier has no PITR, so this pair is production's only undo.
///
/// Auth is dumped **data-only and table-by-table**, never `--schema=auth`: a
/// fresh Supabase project already owns that schema (as `supabase_auth_admin`,
/// with its own version of the tables), so restoring auth DDL collides on
/// ownership before it reaches a single row.
///
/// What is **not** covered, stated rather than implied: Storage objects. The
/// `storage.objects` rows ride in neither dump and the bytes live in S3, so a
/// restore comes back with recipes whose `cover_image_url` points at nothing.
const _dumps = <({String name, List<String> args})>[
  (name: 'public', args: ['--schema=public', '--no-owner', '--no-privileges']),
  (
    name: 'auth',
    args: ['--data-only', '--table=auth.users', '--table=auth.identities'],
  ),
];

/// Steps applied inside a **single transaction** (`psql -1`), so a failure
/// halfway through a file rolls the whole file back (OPT-T6).
///
/// `ON_ERROR_STOP=1` already stops the run at the first error, but without `-1`
/// everything before it has committed: a schema apply that dies two thirds of
/// the way through leaves two thirds of a schema, and the next run starts from
/// a state nothing describes.
///
/// The sim files are **exempt** and must stay that way — they open and close
/// their own transactions around the bulk load (and toggle triggers on the
/// tables they write), which `-1` would nest and break. `rls` is exempt for the
/// same reason and a sharper one: its `rollback` *is* the cleanup.
const _transactional = {
  'create',
  'seed',
  'recipes',
  'nutrition',
  'drop',
  'clean',
  // One transaction per corpus shard, matching the `-1` in the hand-run form
  // CLAUDE.md documents. The shards carry no transaction control of their own
  // (they are flat `select import_recipe(...)` lists), and B110 is the reason
  // this matters: one malformed scraped page aborts its batch, and without `-1`
  // the 300 rows ahead of it have already committed. The import is idempotent,
  // so a re-run would finish the job either way — but "the next run starts from
  // a state nothing describes" is the exact thing OPT-T6 added `-1` to prevent.
  'corpus',
};

/// Whether every `psql` invocation runs inside `postgres:17-alpine` rather than
/// using a client from PATH. Set once by the global `--docker` flag.
///
/// This is not a convenience flag (B033). On a Windows machine with no
/// PostgreSQL client installed, the only `psql` available is the one inside the
/// local Supabase stack's container — and that one is **15.8** while the hosted
/// project runs **17.6**. `psql` tolerates that gap where `pg_dump` does not, so
/// the stack's client appears to work right up until the day you need a backup
/// (B079). Running the client from a pinned image whose major matches the server
/// makes every `db:*` action behave the same from PowerShell and from Bash, with
/// no shell in the path to re-encode a multibyte character (B074).
bool _useDockerPsql = false;

/// The repo root, mounted read-only at `/repo` inside the container so that the
/// repo-relative `-f` paths in [_files] and [_directories] resolve unchanged.
final String _repoRoot = Directory.current.absolute.path;

Future<int> _psql(
  String url,
  List<String> args, {
  bool singleTransaction = false,
}) async {
  final psqlArgs = <String>[
    '-v',
    'ON_ERROR_STOP=1',
    if (singleTransaction) '-1',
    ...args,
  ];

  if (!_useDockerPsql) {
    final proc = await Process.start('psql', [
      url,
      ...psqlArgs,
    ], mode: ProcessStartMode.inheritStdio);
    return proc.exitCode;
  }

  // Inside a container `127.0.0.1` is the container itself, so a loopback URL
  // has to be pointed back at the host; a hosted URL is left alone, which is
  // the case this form exists for.
  final target = _dockerReachable(url);
  final proc = await Process.start('docker', [
    'run',
    '--rm',
    '-i',
    if (target != url) '--add-host=host.docker.internal:host-gateway',
    // Read-only: this mount carries the SQL in, never anything out.
    '-v',
    '$_repoRoot:/repo:ro',
    '-w',
    '/repo',
    'postgres:17-alpine',
    'psql',
    target,
    ..._containerPaths(psqlArgs),
  ], mode: ProcessStartMode.inheritStdio);
  return proc.exitCode;
}

/// [args] with every `-f` operand rewritten to its path inside the container.
///
/// Paths in [_files] / [_directories] are repo-relative and may arrive with
/// Windows separators, which `psql` inside a Linux container cannot open.
List<String> _containerPaths(List<String> args) {
  final out = <String>[];
  for (var i = 0; i < args.length; i++) {
    out.add(args[i]);
    if (args[i] == '-f' && i + 1 < args.length) {
      out.add('/repo/${args[i + 1].replaceAll(r'\', '/')}');
      i++;
    }
  }
  return out;
}

Future<int> _applyFile(
  String url,
  String step, {
  Map<String, String> vars = const {},
}) async {
  final dir = _directories[step];
  if (dir != null) return _applyDirectory(url, step, dir);

  final path = _files[step]!;
  if (!File(path).existsSync()) {
    stderr.writeln('Missing SQL file: $path');
    return 1;
  }
  stdout.writeln('▶ $step  ($path)');
  return _psql(url, [
    for (final entry in vars.entries) ...['-v', '${entry.key}=${entry.value}'],
    '-f',
    path,
  ], singleTransaction: _transactional.contains(step));
}

/// psql `-v` variables a given step needs, derived from the command-line flags.
///
/// Both consumers default themselves when the variable is absent
/// (`\if :{?strict}` / `\if :{?confirm}`), so passing nothing is a valid state
/// and a hand-run `psql -f` behaves the same as this wrapper — the same
/// principle as the sim reading its knobs from `sim.config`.
Map<String, String> _stepVars(
  String step, {
  required bool confirmed,
  required bool strict,
}) => switch (step) {
  // Reports by default and only FAILS under `--strict`, because `db:audit` is
  // the command someone runs to find out what is in a database — including
  // right after `db:sim`, which fabricates a population on purpose. An
  // informational command that exits non-zero for doing its job gets ignored.
  //
  // `reset` forces strict on (see main): there the claim being made is that a
  // default apply path CANNOT fabricate a row, and a claim that only prints is
  // not a gate.
  'audit' => {'strict': strict ? 'on' : 'off'},
  'purge:fake:rows' => {'confirm': confirmed ? 'yes' : 'no'},
  _ => const {},
};

/// Applies every `.sql` file in [dir], sorted by name — the same order the
/// Supabase CLI uses, so `melos run db:create` and `supabase db reset` cannot
/// disagree about what "the schema" is.
///
/// It applies **all** of them, including ones this database has already seen:
/// nothing here tracks migration history (the CLI's `schema_migrations` table
/// does that for `supabase db reset` / `db push`). That is why every migration
/// has to stay idempotent — see `supabase/migrations/README.md`. On a hosted
/// database with real data, prefer applying only the new file: re-running the
/// baseline is safe but re-runs its backfills, which is the cost OPT-A9 exists
/// to stop paying on every change.
Future<int> _applyDirectory(String url, String step, String dir) async {
  final directory = Directory(dir);
  if (!directory.existsSync()) {
    stderr.writeln('Missing SQL directory: $dir');
    return 1;
  }
  // Sorted by full path, which sorts by filename here because the directory
  // prefix is identical — that is what makes `0002_` follow `0001_`, and why
  // migrations are numbered rather than named.
  final files =
      directory
          .listSync()
          .whereType<File>()
          .where((f) => f.path.toLowerCase().endsWith('.sql'))
          .map((f) => f.path)
          .toList()
        ..sort();

  if (files.isEmpty) {
    stderr.writeln('No .sql files in $dir');
    return 1;
  }

  // One transaction **per file**, not one across the directory: a migration is
  // the unit that has to be all-or-nothing, and 0002 failing must not undo 0001
  // on a database that had never seen either.
  for (final path in files) {
    stdout.writeln('▶ $step  ($path)');
    final code = await _psql(url, [
      '-f',
      path,
    ], singleTransaction: _transactional.contains(step));
    if (code != 0) return code;
  }
  return 0;
}

/// Writes the run's knobs into `sim.config` before the generator reads them.
/// The SQL deliberately reads its configuration from a table rather than from
/// psql `-v` variables, so that a hand-run file behaves the same as this
/// wrapper does.
Future<int> _configureSim(String url, String? preset, int? seed) async {
  final sets = <String>[
    if (preset != null) "('preset', '$preset')",
    if (seed != null) "('seed', '$seed')",
  ];
  if (sets.isEmpty) return 0;
  stdout.writeln('▶ sim:config  (${sets.join(', ')})');
  return _psql(url, [
    '-c',
    'insert into sim.config (key, value) values ${sets.join(', ')} '
        'on conflict (key) do update set value = excluded.value',
  ]);
}

/// Dumps [_dumps] into [outDir], timestamped, and returns 0 on success.
///
/// [stamp] is passed in rather than read here so the two files of one run share
/// a name, and [useDocker] runs the dump inside `postgres:17-alpine` instead of
/// from PATH. That is not a convenience: `pg_dump` **aborts on a server major
/// newer than its own**, the hosted project runs 17.x, and the client inside the
/// local Supabase stack is 15.8 (B079) — so on a machine whose only client is
/// the stack's, the container is the only form that can back up production at
/// all. `psql` tolerates that gap, which is exactly why the mismatch goes
/// unnoticed until the day it matters.
Future<int> _backup(
  String url,
  String outDir,
  String stamp, {
  required bool useDocker,
}) async {
  final dir = Directory(outDir);
  if (!dir.existsSync()) dir.createSync(recursive: true);
  final absolute = dir.absolute.path;

  // Inside a container, `127.0.0.1` is the container. A loopback URL therefore
  // has to be rewritten to reach the host's stack, and the gateway alias has to
  // be added because it is not automatic outside Docker Desktop. Hosted URLs
  // are untouched — they are the case this form exists for.
  final target = useDocker ? _dockerReachable(url) : url;
  final hostAlias =
      useDocker && target != url
          ? ['--add-host=host.docker.internal:host-gateway']
          : const <String>[];

  for (final dump in _dumps) {
    final file = '${dump.name}_$stamp.sql';
    stdout.writeln('▶ backup  ($outDir/$file)');
    final Process proc;
    if (useDocker) {
      proc = await Process.start('docker', [
        'run',
        '--rm',
        ...hostAlias,
        // The output directory is mounted rather than streamed, so the bytes
        // never pass through a shell that could re-encode them (B074).
        '-v',
        '$absolute:/backup',
        'postgres:17-alpine',
        'pg_dump',
        target,
        ...dump.args,
        '-f',
        '/backup/$file',
      ], mode: ProcessStartMode.inheritStdio);
    } else {
      proc = await Process.start('pg_dump', [
        url,
        ...dump.args,
        '-f',
        '$outDir/$file',
      ], mode: ProcessStartMode.inheritStdio);
    }
    final code = await proc.exitCode;
    if (code != 0) return code;
  }

  stdout.writeln(
    'Restore order is auth BEFORE public — the FKs point that way.\n'
    'Storage objects are NOT in these files; see README.md#backups.',
  );
  return 0;
}

/// [url] with a loopback host swapped for `host.docker.internal`, unchanged
/// otherwise. Returns the input on an unparseable string rather than guessing.
String _dockerReachable(String url) {
  try {
    final uri = Uri.parse(url);
    if (uri.host != '127.0.0.1' && uri.host != 'localhost') return url;
    return uri.replace(host: 'host.docker.internal').toString();
  } on FormatException {
    return url;
  }
}

/// The host being targeted, with any credential stripped. `db:*` fires at
/// whatever SUPABASE_DB_URL points at with no prod guard (CLAUDE.md Gotcha 7),
/// so the least this can do is say where.
String _describeTarget(String url) {
  try {
    final uri = Uri.parse(url);
    return '${uri.host}:${uri.port}${uri.path}';
  } on FormatException {
    return '(unparseable connection string)';
  }
}

