Future<void> main(List<String> args) async {
  final url = Platform.environment['SUPABASE_DB_URL'];
  if (url == null || url.isEmpty) {
    stderr.writeln(
      'SUPABASE_DB_URL is not set.\n'
      'Get it from Supabase -> Project Settings -> Database -> Connection string (URI),\n'
      'then e.g.  \$env:SUPABASE_DB_URL = "postgresql://postgres:<pwd>@db.<ref>.supabase.co:5432/postgres"',
    );
    exit(2);
  }

  final positional = args.where((a) => !a.startsWith('--')).toList();
  final flags = args.where((a) => a.startsWith('--')).toList();
  final action = positional.isEmpty ? 'help' : positional.first;

  String? optionOf(String name) {
    final hit = flags.where((f) => f.startsWith('--$name=')).toList();
    return hit.isEmpty ? null : hit.first.substring(name.length + 3);
  }

  final preset = optionOf('preset');
  final seedOpt = optionOf('seed');
  final outDir = optionOf('out') ?? 'backups';
  final confirmed = flags.contains('--yes');

  // Applies to every step, not just `backup`: with no PostgreSQL client on
  // PATH this is the only way `db:*` runs at all on this machine (B033), and
  // against hosted it is the form that keeps the client major matched to the
  // server (B079).
  _useDockerPsql = flags.contains('--docker');

  if (seedOpt != null && int.tryParse(seedOpt) == null) {
    stderr.writeln('--seed must be an integer (got "$seedOpt")');
    exit(64);
  }
  const presets = {'tiny', 'small', 'medium', 'large'};
  if (preset != null && !presets.contains(preset)) {
    stderr.writeln(
      '--preset must be one of ${presets.join(', ')} (got "$preset")',
    );
    exit(64);
  }

  // Read-only and file-producing rather than file-applying, so it short-circuits
  // the step machinery below entirely.
  if (action == 'backup') {
    stdout.writeln('target: ${_describeTarget(url)}');
    final now = DateTime.now().toUtc();
    String two(int v) => v.toString().padLeft(2, '0');
    final stamp =
        '${now.year}${two(now.month)}${two(now.day)}'
        'T${two(now.hour)}${two(now.minute)}${two(now.second)}Z';
    final code = await _backup(
      url,
      outDir,
      stamp,
      useDocker: flags.contains('--docker'),
    );
    if (code != 0) {
      stderr.writeln(
        '✖ backup failed (exit $code).\n'
        '  No pg_dump on PATH? Re-run with --docker, which uses '
        'postgres:17-alpine —\n'
        '  and note a client older than the server aborts outright (B079).',
      );
      exit(code);
    }
    stdout.writeln('✔ done');
    return;
  }

  final steps =
      _pipelines[action] ??
      ((_files.containsKey(action) || _directories.containsKey(action))
          ? [action]
          : const <String>[]);

  if (action == 'help' || steps.isEmpty) {
    _usage();
    exit(action == 'help' ? 0 : 64);
  }

  if (_destructive.contains(action) && !confirmed) {
    stderr.writeln(
      '✖ $action deletes rows from auth.users on ${_describeTarget(url)}.\n'
      '  auth.users has no undo. Re-run with --yes to confirm.',
    );
    exit(3);
  }

  if (_needsConfirmation.contains(action) && !confirmed) {
    stderr.writeln(
      '✖ $action writes the schema, the food registry, the curated recipes and\n'
      '  the whole captured corpus to ${_describeTarget(url)}.\n'
      '  Take a backup first (`db:backup -- --docker --out=<dir>`); the free\n'
      '  tier has no PITR, so that dump is the only undo.\n'
      '  Re-run with --yes to confirm.',
    );
    exit(3);
  }

  stdout.writeln('target: ${_describeTarget(url)}');

  // Flatten first: a pipeline entry may itself be a pipeline (`reset` contains
  // `sim`), and the sim:generate hook below has to see the real leaf rather
  // than the group that contains it.
  final leaves = <String>[
    for (final step in steps) ...(_pipelines[step] ?? [step]),
  ];

  for (final leaf in leaves) {
    // The generator reads its knobs from sim.config, so they have to be written
    // after the schema exists and before the generator runs.
    if (leaf == 'sim:generate') {
      final code = await _configureSim(
        url,
        preset,
        seedOpt == null ? null : int.parse(seedOpt),
      );
      if (code != 0) {
        stderr.writeln('✖ sim:config failed (exit $code)');
        exit(code);
      }
    }
    final code = await _applyFile(
      url,
      leaf,
      vars: _stepVars(
        leaf,
        confirmed: confirmed,
        // `reset` and `hosted:deploy` assert rather than report: the contract
        // of both is that what they produce contains nothing fabricated, and
        // for the second of those the database on the other end is production.
        strict:
            flags.contains('--strict') ||
            action == 'reset' ||
            action == 'hosted:deploy',
      ),
    );
    if (code != 0) {
      stderr.writeln('✖ $leaf failed (exit $code)');
      exit(code);
    }
  }
  stdout.writeln('✔ done');
}
